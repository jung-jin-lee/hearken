def ccel_url(path):
    """CCEL 경로에서 URL 구성."""
    if "/" in path:
        # e.g. "spurgeon/treasury7" -> ccel/s/spurgeon/treasury7/...
        parts = path.split("/")
        author = parts[0]
        work = parts[1]
        return f"https://ccel.org/ccel/{author[0]}/{author}/{work}/cache/{work}.txt"
    else:
        # e.g. "npnf201" -> ccel/s/schaff/npnf201/...
        return f"https://ccel.org/ccel/s/schaff/{path}/cache/{path}.txt"


def gutenberg_url(gid):
    return f"https://www.gutenberg.org/cache/epub/{gid}/pg{gid}.txt"


def archive_url(aid):
    return f"https://archive.org/download/{aid}/{aid}_djvu.txt"


def parse_catalog():
    """카탈로그 마크다운에서 도서 목록 파싱."""
    text = CATALOG.read_text(encoding="utf-8")
    # 테이블 행 파싱: | # | slug | 영문 제목 | 한국어 제목 | 저자 | 사망 | 챕터 | 소스 |
    pattern = re.compile(
        r"\|\s*(\d+)\s*\|\s*([a-z0-9-]+)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*(\d+)\s*\|\s*([^|]+?)\s*\|"
    )
    books = []
    for m in pattern.finditer(text):
        num = int(m.group(1))
        slug = m.group(2).strip()
        title_en = m.group(3).strip()
        title_kr = m.group(4).strip()
        author = m.group(5).strip()
        death_year = m.group(6).strip()
        chapters = int(m.group(7))
        source = m.group(8).strip()
        books.append({
            "num": num,
            "slug": slug,
            "title_en": title_en,
            "title_kr": title_kr,
            "author": author,
            "death_year": death_year,
            "chapters": chapters,
            "source": source,
        })
    return books


def determine_source_type(source_str):
    """소스 문자열에서 source_type 결정."""
    s = source_str.lower()
    if "ccel" in s and "gutenberg" not in s and "archive" not in s:
        return "ccel"
    if "gutenberg" in s and "ccel" not in s and "archive" not in s:
        return "gutenberg"
    if "archive" in s and "ccel" not in s and "gutenberg" not in s:
        return "archive"
    # 복합 소스: 우선순위 결정
    if "ccel" in s:
        return "ccel"
    if "gutenberg" in s:
        return "gutenberg"
    return "archive"


def resolve_url(slug, source_type):
    """slug과 source_type으로 URL 결정."""
    # CCEL paths
    if slug in CCEL_PATHS:
        return ccel_url(CCEL_PATHS[slug])
    # Gutenberg IDs
    if slug in GUTENBERG_IDS:
        return gutenberg_url(GUTENBERG_IDS[slug])
    # Archive IDs
    if slug in ARCHIVE_IDS:
        return archive_url(ARCHIVE_IDS[slug])
    # JFB CCEL fallback
    if slug.startswith("jfb-"):
        return ccel_url(f"jamieson/jfb")
    # Fallback: construct best guess
    if source_type == "ccel":
        # Try to guess CCEL path from slug
        return f"https://ccel.org/ccel/{slug.replace('-', '/')}"
    elif source_type == "gutenberg":
        return f"https://www.gutenberg.org/ebooks/search/?query={slug.replace('-', '+')}"
    else:
        return f"https://archive.org/download/{slug}/{slug}_djvu.txt"


