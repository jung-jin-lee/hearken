def make_note(slug, title_kr, title_en, author):
    """간단한 설명 생성."""
    return f"{title_kr}. {author}의 저작."


def main():
    # p3a slugs 로드
    p3a = json.loads(P3A.read_text())
    p3a_slugs = set(b["slug"] for b in p3a)
    print(f"p3a: {len(p3a_slugs)}권 제외")

    # 카탈로그 파싱
    books = parse_catalog()
    print(f"카탈로그 파싱: {len(books)}권")

    # p3a 제외
    remaining = [b for b in books if b["slug"] not in p3a_slugs]
    print(f"p3b 대상: {len(remaining)}권")

    # 매니페스트 생성
    manifest = []
    for b in remaining:
        source_type = determine_source_type(b["source"])
        url = resolve_url(b["slug"], source_type)
        author_kr = make_author_kr(b["author"])

        entry = {
            "slug": b["slug"],
            "title": b["title_kr"],
            "title_en": b["title_en"],
            "author_kr": author_kr,
            "author_en": b["author"],
            "year": b["death_year"],
            "url": url,
            "source_type": source_type,
            "note": make_note(b["slug"], b["title_kr"], b["title_en"], author_kr),
        }
        manifest.append(entry)

    # 저장
    OUT.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\n✅ {OUT} 생성 완료: {len(manifest)}권")

    # 소스 타입별 통계
    from collections import Counter
    types = Counter(b["source_type"] for b in manifest)
    print(f"소스별: {dict(types)}")

    # URL 미해결 항목
    unresolved = [b for b in manifest if "search" in b["url"] or b["url"].startswith("https://ccel.org/ccel/")]
    if unresolved:
        print(f"\n⚠️ URL 미해결: {len(unresolved)}권")
        for b in unresolved[:10]:
            print(f"  {b['slug']}: {b['url'][:80]}")


if __name__ == "__main__":
    main()
